/* ------------------------------------------------------- active run ---- */

/**
 * The run the viewport is currently showing. Field overlays are drawn by
 * modules (overlays.js, tools.js) that legitimately do not hold a RunResult,
 * but a field's provenance depends on the RunSpec that produced it — a KDE
 * vascular field is not the same claim as a discrete one. Parked here so those
 * call sites stay argument-free.
 */
let ACTIVE_RUN = null;
export function setActiveRun(run) { ACTIVE_RUN = run || null; }

/**
 * Provenance of a FIELD OVERLAY, run-aware.
 *
 * js/fields.js carries the BASE claim for each field. It is a static table, so
 * on its own it cannot know that this particular run used a vascular mode that
 * did not converge, or an oxygen route that is a transcriptional surrogate —
 * and a static `computed` chip on a field whose own metrics are escalating to
 * `assumed` is the escalation rule failing in the one place where the assumed
 * quantity IS the thing on screen.
 */
export function fieldProvenance(name, run) {
  const meta = fieldMeta(name || '');
  const r = run || ACTIVE_RUN;
  const spec = (r && r.spec) || {};
  const rep = (r && r.report) || {};
  let kind = KINDS.includes(meta.provenance) ? meta.provenance : 'unknown';
  const reasons = [];

  // Same conditions metricProvenance() uses, so the field and the metrics
  // integrated out of it can never disagree.
  if (spec.vascular_mode === 'kde'
      && (name === 'vascular_density' || name === 'oxygen' || name === 'drug_auc')) {
    kind = 'assumed';
    reasons.push('vascular_mode=kde did not converge under grid refinement; the discrete reconstruction is the production default. This overlay IS that non-converged field (or is solved on top of it).');
  }
  if (rep.oxygen && rep.oxygen.is_surrogate
      && (name === 'oxygen' || name === 'drug_auc')) {
    kind = 'assumed';
    reasons.push('oxygen_mode=markers: this is a transcriptional SURROGATE for pO2, never calibrated against a measured oxygen tension on this tissue.');
  }
  if (name === 'oxygen' && rep.oxygen && rep.oxygen.caveat) {
    reasons.push(rep.oxygen.caveat);
  }
  const why = [describe(kind), meta.source, meta.note, ...reasons].filter(Boolean).join('\n\n');
  return { kind, why, meta };
}


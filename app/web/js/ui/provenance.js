// provenance.js — the measured / computed / assumed decision, in ONE place.
//
// The product claim is that a number never appears without saying where it
// came from. That is only credible if the classification is a single readable
// rule set rather than a chip hard-coded next to each render site.
//
//   measured   — came off an instrument, ON THIS SPECIMEN. Nothing in the model
//                chain touched its value.
//   literature — a published measured value, but measured on OTHER material
//                (GDSC cell lines, a penetration half-distance from a paper).
//                Real data; not this tissue. Kept distinct from `measured`
//                because a green chip on an IC50 sitting next to a green chip
//                on a cell count implies both came from this section, and only
//                one of them did.
//   computed   — a deterministic function of measured inputs through the
//                model. Reproducible; only as good as its inputs.
//   assumed    — a value we chose. Includes calibration constants, defaults,
//                surrogates, and any number that is an upper bound because a
//                resistance term was set to unity rather than observed.
//   synthetic  — NOT DATA. Fabricated by js/mock.js because the backend did
//                not answer. It outranks every other kind: see setSynthetic().
//
// The escalation rule matters more than the taxonomy: a computed quantity
// that depends on an assumed input is reported as ASSUMED, not computed. That
// rule is applied by metricProvenance(), reportProvenance() and
// fieldProvenance() — and those three share their conditions on purpose, so a
// field overlay can never read `computed` while the metric integrated out of
// that same field reads `assumed`.

import { h } from '../util/dom.js';
import { fieldMeta } from '../fields.js';

export const KINDS = ['measured', 'literature', 'computed', 'assumed', 'unknown'];

/* --------------------------------------------------------- synthetic --- */

/**
 * The STUB latch. When js/api.js falls back to js/mock.js there is no measured
 * anything on screen — geometry, fields, metrics and report are all fabricated
 * by a seeded PRNG. Rather than audit every render site for a stub branch, the
 * latch is read HERE, by the one function every provenance chip in the app is
 * built with. Flipping it re-labels every chip in every panel at once, which is
 * the only way this stays true as panels are added.
 */
let SYNTHETIC = null;

export function setSynthetic(on, why) { SYNTHETIC = on ? { why: why || '' } : null; }
export function isSynthetic() { return !!SYNTHETIC; }

export function chip(kind, why) {
  const k = KINDS.includes(kind) ? kind : 'unknown';
  if (SYNTHETIC) {
    return h('span.chip.synthetic', {
      title: `${describe('synthetic')}\n\n${SYNTHETIC.why}\n\n`
        + `Against a live backend this quantity would have read "${k}". `
        + `It does not read that now, because there is no backend and no data behind it.`
        + (why ? `\n\nLive-mode note: ${why}` : ''),
    }, 'synthetic');
  }
  return h('span.chip.' + k, { title: why || describe(k) }, k);
}

export function describe(kind) {
  switch (kind) {
    case 'measured': return 'Measured: an instrument produced this value directly, on THIS specimen.';
    case 'literature': return 'Literature: a published measured value, but measured on other material (cell lines, another tissue), not on this section.';
    case 'computed': return 'Computed: a deterministic model function of measured inputs.';
    case 'assumed': return 'Assumed: a value we chose — default, calibration constant, surrogate, or an upper bound standing in for an unmeasured term.';
    case 'synthetic': return 'SYNTHETIC: fabricated by js/mock.js, not data. The backend did not answer, so this number was generated by a seeded PRNG against the shape of API_CONTRACT.md. It is not a result and must not be read, quoted, or exported as one.';
    default: return 'Provenance not stated by the backend for this quantity.';
  }
}


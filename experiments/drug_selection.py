"""Per-patient DRUG SELECTION — the real precision-oncology task, and the regime
where spatial transport should finally earn its keep.

Question: given a patient's tumor microenvironment, can the mechanistic sim pick
the drug that actually works BETTER than a potency shortcut that ignores delivery?

This is the task the earlier single-drug Stage 0 could not test. Two patients with
the same tumor but different vascularization / BBB integrity need DIFFERENT drugs:
a very potent but poorly-delivered drug (doxorubicin, low BBB) loses to a weaker
but penetrant one (temozolomide) unless the tumor's vessels are leaky.

HONESTY / anti-circularity design:
- The ground-truth best drug is generated by an INDEPENDENT algebraic delivery
  model (different functional form from the sim's PDE) + noise. The sim never sees
  it. Both legitimately use each drug's real properties (IC50, BBB), but the
  DISCRIMINATOR is delivery physics, which the sim computes mechanistically and the
  potency baseline ignores. The sim is not guaranteed to win.
- Synthetic ground truth => this demonstrates a CAPABILITY (the model can recover
  delivery-driven drug choice) and quantifies WHEN transport beats the shortcut. It
  is not evidence about real patients (that still needs paired clinical data).
"""
import warnings; warnings.filterwarnings("ignore")
import json
import numpy as np

from tmesim.core import SimConfig, PKConfig, PDEConfig
from tmesim.data.synthetic import generate_synthetic_cohort
from tmesim.molecular import library
from tmesim.molecular.binding_site_barrier import apply_barrier_to_drugparams
from tmesim.validation.calibration import calibrate_alpha, calibrated_drugparams
from tmesim.sim.engine import simulate_response

PANEL = ["temozolomide", "lomustine", "cisplatin", "methotrexate", "doxorubicin"]
N = 24
DOSE = 30.0          # global plasma-equivalent dose (uM-ish)
TOTAL_TIME = 600.0
rng = np.random.default_rng(0)

# --- realistic DrugParams (structure -> mesh D -> measured IC50 -> calibrated loss -> barrier) ---
alpha = calibrate_alpha(target_um=45.0, drug="doxorubicin")
drug_params, drug_meta = {}, {}
for name in PANEL:
    mol = library.get_molecule(name)
    dp = apply_barrier_to_drugparams(calibrated_drugparams(name, alpha=alpha), mol)
    drug_params[name] = dp
    drug_meta[name] = dict(mw=float(mol.get("mw")), ic50=float(dp.ic50), bbb=float(dp.bbb_penetrance))
print("drug panel (realistic params):")
for n in PANEL:
    m = drug_meta[n]
    print(f"  {n:14s} MW={m['mw']:7.0f}  IC50={m['ic50']:7.2f}uM  BBB={m['bbb']:.3f}")


def hill(exposure, ic50, h=1.3):
    e = np.maximum(exposure, 0.0)
    return e**h / (e**h + ic50**h)


def ground_truth_kill(vasc, ecm, bbb_disruption, sens, dm):
    """INDEPENDENT algebraic ground truth (NOT the sim). Delivery needs vessels;
    a drug reaches tissue via tumor BBB disruption OR its own BBB penetrance; large
    drugs are hindered by dense ECM. Kill = sensitivity * Hill(delivered dose)."""
    size = dm["mw"] / 500.0
    bbb_term = bbb_disruption + (1.0 - bbb_disruption) * dm["bbb"]
    delivery = vasc * bbb_term * np.exp(-1.4 * ecm * size)      # in [0,1]-ish
    exposure = delivery * DOSE
    return float(sens * hill(exposure, dm["ic50"]))


# --- build cohort; each patient gets a BBB-disruption level (varies delivery regime) ---
cohort = generate_synthetic_cohort(n=N, seed=0)
patients = []
for i, rec in enumerate(cohort):
    m = rec.micro
    tum = m.cells.tumor_mask()
    col, row = m.domain.to_index(m.cells.x[tum], m.cells.y[tum])
    vasc = float(np.mean(m.fields.vascular_density[row, col]))       # perfusion in tumor
    ecm = float(np.mean(m.fields.ecm_density[row, col]))
    sens = float(np.mean(m.cells.sensitivity[tum]))
    bbb_disruption = float(rng.uniform(0.1, 0.9))                    # patient-specific
    gt = {d: ground_truth_kill(vasc, ecm, bbb_disruption, sens, drug_meta[d]) for d in PANEL}
    noisy = {d: float(np.clip(gt[d] + rng.normal(0, 0.04), 0, 1)) for d in PANEL}
    true_best = max(noisy, key=noisy.get)
    patients.append(dict(idx=i, rec=rec, vasc=vasc, ecm=ecm, bbb_disruption=bbb_disruption,
                         sens=sens, gt=noisy, true_best=true_best))

# --- model predictions ---
# (A) mechanistic sim: run the PDE engine per drug, pick highest predicted kill
# (B) potency-only shortcut: assume perfect delivery -> Hill(DOSE, ic50)*sens (ignores microenv)
# (C) most-potent-drug: always the lowest-IC50 drug (a naive constant policy)
print(f"\nrunning {N} patients x {len(PANEL)} drugs = {N*len(PANEL)} sims ...", flush=True)
for p in patients:
    sim_kill, pot_score = {}, {}
    for d in PANEL:
        cfg = SimConfig(drug=drug_params[d], pk=PKConfig(plasma_peak=1.0),
                        pde=PDEConfig(total_time=TOTAL_TIME), seed=0)
        sim_kill[d] = float(simulate_response(p["rec"].micro, cfg).kill_fraction)
        pot_score[d] = p["sens"] * hill(DOSE, drug_meta[d]["ic50"])   # delivery assumed perfect
    p["sim_best"] = max(sim_kill, key=sim_kill.get)
    p["potency_best"] = max(pot_score, key=pot_score.get)
    p["sim_kill"] = sim_kill

most_potent = min(PANEL, key=lambda d: drug_meta[d]["ic50"])  # constant policy

# --- scoring: top-1 accuracy + mean regret (true kill lost vs the true-best drug) ---
def score(policy_key_or_const):
    hits, regret = 0, []
    for p in patients:
        pick = policy_key_or_const(p)
        hits += (pick == p["true_best"])
        regret.append(p["gt"][p["true_best"]] - p["gt"][pick])
    return hits / len(patients), float(np.mean(regret))

acc_sim, reg_sim = score(lambda p: p["sim_best"])
acc_pot, reg_pot = score(lambda p: p["potency_best"])
acc_fix, reg_fix = score(lambda p: most_potent)
# random policy expectation
acc_rand = float(np.mean([1.0/len(PANEL) for _ in patients]))

print("\n================ DRUG-SELECTION RESULTS ================")
print(f"{'policy':28s} {'top1_acc':>9} {'mean_regret':>12}")
print("-"*52)
print(f"{'mechanistic sim (transport)':28s} {acc_sim:>9.3f} {reg_sim:>12.4f}")
print(f"{'potency-only (no transport)':28s} {acc_pot:>9.3f} {reg_pot:>12.4f}")
print(f"{'always most-potent ('+most_potent[:8]+')':28s} {acc_fix:>9.3f} {reg_fix:>12.4f}")
print(f"{'random (chance)':28s} {acc_rand:>9.3f} {'-':>12}")

# how often does the true best differ from 'just pick the most potent'? (is transport needed?)
frac_transport_matters = float(np.mean([p["true_best"] != most_potent for p in patients]))
best_dist = {d: sum(p["true_best"] == d for p in patients) for d in PANEL}
print(f"\ntrue-best drug varies across patients: {best_dist}")
print(f"fraction of patients where potency-shortcut is WRONG: {frac_transport_matters:.2f}")

verdict = (
    f"Mechanistic sim top-1 {acc_sim:.2f} vs potency-only {acc_pot:.2f} "
    f"(and constant-most-potent {acc_fix:.2f}); regret {reg_sim:.3f} vs {reg_pot:.3f}. "
    + ("Sim BEATS the potency shortcut at picking the deliverable drug."
       if (acc_sim > acc_pot and reg_sim < reg_pot)
       else "Sim does NOT beat the potency shortcut on this cohort.")
)
print("\nVERDICT:", verdict)

out = dict(n=N, panel=PANEL, drug_meta=drug_meta, alpha=alpha,
           acc={"sim": acc_sim, "potency_only": acc_pot, "most_potent": acc_fix, "random": acc_rand},
           regret={"sim": reg_sim, "potency_only": reg_pot, "most_potent": reg_fix},
           frac_transport_matters=frac_transport_matters, best_distribution=best_dist,
           verdict=verdict)
with open("results/drug_selection.json", "w") as f:
    json.dump(out, f, indent=2, default=float)
print("saved results/drug_selection.json")

# --- figure ---
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
fig, ax = plt.subplots(1, 2, figsize=(11, 4.5))
labels = ["mechanistic\nsim", "potency-only\n(no transport)", f"always\n{most_potent[:10]}", "random"]
accs = [acc_sim, acc_pot, acc_fix, acc_rand]
colors = ["#2ca02c", "#d62728", "#ff7f0e", "#999999"]
ax[0].bar(labels, accs, color=colors)
for i, v in enumerate(accs):
    ax[0].text(i, v+0.01, f"{v:.2f}", ha="center", fontsize=10)
ax[0].set_ylabel("top-1 drug-selection accuracy"); ax[0].set_ylim(0, 1)
ax[0].set_title("Picking the right drug per patient")
regs = [reg_sim, reg_pot, reg_fix]
ax[1].bar(labels[:3], regs, color=colors[:3])
for i, v in enumerate(regs):
    ax[1].text(i, v+0.001, f"{v:.3f}", ha="center", fontsize=10)
ax[1].set_ylabel("mean regret (true kill lost)"); ax[1].set_title("Cost of the wrong choice")
fig.suptitle("Per-patient drug selection: does modeling delivery beat a potency shortcut?", fontsize=12)
plt.tight_layout(); fig.savefig("results/drug_selection.png", dpi=130)
print("wrote results/drug_selection.png")

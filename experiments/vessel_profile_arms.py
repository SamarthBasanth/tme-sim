"""Both-arms (transvascular exchange OFF vs ON) regeneration of the perivascular
drug-gradient numbers in ``results/vessel_profile.md``.

Why this script exists
======================
``results/vessel_profile.md`` is generated by
:mod:`tmesim.validation.vessel_profile`, which has **two different propagation
categories inside one file** (see :data:`tmesim.validation.propagation.DECLARATIONS`):

* ``vessel_profile.analyze_drug``  -> ``sim.engine.simulate_response``  -> **PROPAGATED**.
  ``PDEConfig(transvascular_exchange=True)`` genuinely reaches the solver on the
  real-tissue arms and on the KDE-bandwidth sweep (which also calls ``analyze_drug``).
* ``vessel_profile.isolated_vessel_profile`` -> ``simulate_drug_transport``
  DIRECTLY, with no ``exchange_k`` -> **INERT**. The flag is a silent no-op; an
  "on vs off" comparison there is a run compared against itself.

``results/transvascular_exchange_revalidation.md`` section 6 lists
``vessel_profile`` on the silent-no-op list, which is true *of that second
function only*. So this script does two different things for the two halves and
says which is which, rather than averaging them into one false whole-file claim.

Every run below is wrapped in :func:`tmesim.validation.propagation.instrument`,
which counts solver calls and records whether ``exchange_k`` actually crossed the
function boundary, and every OFF/ON pair is compared with
:func:`tmesim.validation.propagation.digest` -- a BIT-level structural hash. A
pair whose digests match is reported as such and is not allowed to masquerade as
"exchange changes nothing".

The isolated single-vessel control needs care
=============================================
``_uniform_micro`` sets ``vascular_density`` to ZERO everywhere and hand-paints a
unit line source instead. So the engine-faithful injection,
``exchange_coefficient(micro, drug)``, is IDENTICALLY ZERO there and would give a
vacuous "invariant" -- exchange applied to nothing. The control's own
normalisation is ``source = vascular_density * bbb_penetrance * Cp = src`` with a
peak of 1.0, so the self-consistent permeability is ``PS = src / Cp``. ``Cp`` is
not defined in that geometry, so BOTH readings are run:

* ``Cp = 1``          -> ``exchange_k = src``                (PS = 1 s^-1 on the vessel line)
* ``Cp = 1/bbb``      -> ``exchange_k = src * bbb_penetrance`` (drug-specific PS)

If the decay length is invariant under both, the invariance is not an artefact of
one arbitrary normalisation.

Usage
-----
    ./.venv/bin/python -u experiments/vessel_profile_arms.py --out <json> [--stage all|iso|arms|bandwidth]

Writes nothing into ``results/``; the caller transcribes the numbers.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import time
from typing import Dict, List, Optional, Sequence

import numpy as np

from tmesim.core.config import PDEConfig
from tmesim.core import CellPopulation, Domain, Microenvironment, TissueFields
from tmesim.reconstruct.real_fields import build_real_fields
from tmesim.reconstruct.real_pipeline import reconstruct_real
from tmesim.treatment.drugs import exchange_coefficient
from tmesim.physics.diffusion import simulate_drug_transport
from tmesim.validation import vessel_profile as vp
from tmesim.validation.calibration import calibrate_alpha
from tmesim.validation.propagation import digest, instrument

DRUGS = ("doxorubicin", "temozolomide")


def _log(msg: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def _n(x, nd: int = 2) -> str:
    """Format an optional/None/non-finite number without ever raising."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "n/a"
    return f"{v:.{nd}f}" if math.isfinite(v) else "n/a"


def _jsonable(obj):
    if isinstance(obj, dict):
        return {k: _jsonable(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_jsonable(v) for v in obj]
    if isinstance(obj, np.ndarray):
        return None  # never serialise fields; only summaries
    if isinstance(obj, (np.floating, float)):
        f = float(obj)
        return f if math.isfinite(f) else None
    if isinstance(obj, (np.integer, int)):
        return int(obj)
    if isinstance(obj, (np.bool_, bool)):
        return bool(obj)
    return obj


def _fit_summary(pf: Dict) -> Dict:
    """Reduce a ``profile_fits`` dict to the numbers the report quotes."""
    ef = pf.get("exp_floor", {}) or {}
    near = pf.get("near_exp", {}) or {}
    lin = pf.get("linear_null", {}) or {}
    prof = pf.get("profile", {}) or {}
    d_all, m_all, w_all = vp.usable_bins(prof) if prof else (
        np.array([]), np.array([]), np.array([]))
    return {
        "empirical_d_half_um": pf.get("empirical_d_half_um"),
        "perivascular_mean": pf.get("perivascular_mean"),
        "plateau_fraction": pf.get("plateau_fraction"),
        "exp_floor_L_um": ef.get("L_um"),
        "exp_floor_d_half_um": ef.get("d_half_um"),
        "exp_floor_d_half_total_um": ef.get("d_half_total_um"),
        "exp_floor_floor_fraction": ef.get("floor_fraction"),
        "exp_floor_r2_linear": ef.get("r2_linear_space"),
        "exp_floor_error": ef.get("error"),
        "near_L_um": near.get("L_um"),
        "near_d_half_um": near.get("d_half_um"),
        "near_r2_linear": near.get("r2_linear_space"),
        "near_r2_log": near.get("r2_log"),
        "near_error": near.get("error"),
        "linear_null_r2_linear": lin.get("r2_linear_space"),
        "n_usable_bins": int(d_all.size),
        "max_usable_bin_um": (float(d_all.max()) if d_all.size else None),
    }


# --------------------------------------------------------------------------- #
# Stage 1 -- the isolated single-vessel control (the INERT half of the file)
# --------------------------------------------------------------------------- #
def _iso_run(name: str, alpha: float, ecm: float, mode: str) -> Dict:
    """One isolated single-vessel run.

    ``mode`` is one of:
      ``off``          shipped path, flag off              (the published arm)
      ``flag_only``    PDEConfig(transvascular_exchange=True) and NOTHING else --
                       the silent-no-op control. MUST come out bit-identical to
                       ``off``; if it does not, the trap is not what we think.
      ``ps_engine``    exchange_k = exchange_coefficient(micro, dp) -- the
                       engine-faithful injection, which is identically zero here
                       because ``_uniform_micro`` has vascular_density = 0.
      ``ps_unit``      exchange_k = src              (Cp = 1 reading)
      ``ps_bbb``       exchange_k = src * bbb        (Cp = 1/bbb reading)
    """
    dp, _ = vp.compile_real_drug(name, alpha)
    micro = vp._uniform_micro(ecm, dx_um=vp.DX_UM)
    n = micro.domain.nx
    src = np.zeros((n, n), dtype=np.float64)
    src[:, n // 2] = 1.0

    flag = mode != "off"
    pde = PDEConfig(convection=False, transvascular_exchange=flag, **vp._PDE)
    if mode in ("off", "flag_only"):
        ex = None
    elif mode == "ps_engine":
        ex = np.asarray(exchange_coefficient(micro, dp), dtype=np.float64)
    elif mode == "ps_unit":
        ex = src.copy()
    elif mode == "ps_bbb":
        ex = src * float(dp.bbb_penetrance)
    else:  # pragma: no cover
        raise ValueError(mode)

    # ONE call site, and it ALWAYS passes exchange_k explicitly -- ``None`` for
    # the OFF/flag-only arms (which is exactly what the solver's own default is,
    # so the OFF arm stays bit-identical to the shipped path) and the injected
    # field otherwise. Written this way deliberately: a *bare*
    # ``simulate_drug_transport(...)`` here would be a new undeclared silent-no-op
    # call site, which ``tests/test_propagation.py::
    # test_no_undeclared_direct_solver_callers`` correctly fails on. The whole
    # point of this script is to not re-create the defect it is measuring.
    with instrument() as probe:
        tr = simulate_drug_transport(micro, dp, src, pde, exchange_k=ex)

    auc = np.asarray(tr.auc, dtype=np.float64)
    dist = np.abs(np.arange(n) - n // 2) * float(vp.DX_UM)
    keep = dist <= vp.ISO_MAX_UM
    curve = auc.mean(axis=0)[keep]
    d = dist[keep]
    order = np.argsort(d)
    d_s, c_s = d[order], curve[order]
    uniq = np.unique(d_s)
    mean = np.array([c_s[d_s == u].mean() for u in uniq])
    fit = vp.fit_exponential(uniq[uniq > 0], mean[uniq > 0])

    return {
        "drug": name,
        "mode": mode,
        "flag": flag,
        "exchange_k_max": (float(ex.max()) if ex is not None else None),
        "exchange_k_all_zero": (bool(np.all(ex == 0.0)) if ex is not None else None),
        "bbb_penetrance": float(dp.bbb_penetrance),
        "L_um": fit.get("L_um"),
        "d_half_um": fit.get("d_half_um"),
        "r2_log": fit.get("r2_log"),
        "empirical_d_half_um": vp.empirical_half_distance_um(uniq, mean),
        "perivascular_value": float(mean[0]),
        "auc_sum": float(auc.sum()),
        "auc_digest": digest(auc),
        "solver_calls": probe.solver_calls,
        "exchange_k_calls": probe.exchange_k_calls,
    }


def stage_isolated(alpha: float, ecm: float, drugs: Sequence[str]) -> List[Dict]:
    out = []
    for name in drugs:
        for mode in ("off", "flag_only", "ps_engine", "ps_unit", "ps_bbb"):
            t0 = time.time()
            r = _iso_run(name, alpha, ecm, mode)
            r["seconds"] = time.time() - t0
            _log(f"ISO {name:14s} {mode:10s} L={_n(r['L_um'])} d1/2={_n(r['d_half_um'])} "
                 f"R2log={_n(r['r2_log'], 5)} emp_d1/2={_n(r['empirical_d_half_um'])} "
                 f"peri={r['perivascular_value']:.6g} PSmax={_n(r['exchange_k_max'], 4)} "
                 f"solver={r['solver_calls']} exch_k={r['exchange_k_calls']} "
                 f"digest={r['auc_digest'][:12]}")
            out.append(r)
    return out


# --------------------------------------------------------------------------- #
# Stage 2 -- the real-tissue arms (the PROPAGATED half of the file)
# --------------------------------------------------------------------------- #
def stage_arms(alpha: float, arms: Sequence[Dict], drugs: Sequence[str],
               flags: Sequence[bool], checkpoint) -> List[Dict]:
    out = []
    for arm in arms:
        _log(f"ARM {arm['key']}: building microenvironment (dx={arm['dx_um']}, "
             f"repair={arm['repair']}) ...")
        micro, conn_native, conn_used = vp.build_arm_microenvironment(
            arm["dx_um"], arm["repair"])
        tissue = np.asarray(micro.domain.tissue_mask, dtype=bool)
        vasc = np.asarray(micro.fields.vascular_density, dtype=np.float64)
        endo = vp.endothelial_xy(micro.cells)
        dist = vp.direct_vessel_distance_um(micro.domain, endo)
        vm = vp.vessel_mask_from_density(vasc, tissue, vp.VESSEL_PERCENTILE)
        dist_legacy = vp.distance_from_vessel_um(vm["mask"], micro.domain.dx)
        null = vp.profile_fits(vp.distance_profile(vasc, dist, tissue))
        null_legacy = vp.profile_fits(vp.distance_profile(vasc, dist_legacy, tissue))
        _log(f"ARM {arm['key']}: grid {micro.domain.ny}x{micro.domain.nx} "
             f"tissue={int(tissue.sum()):,}px largest={conn_used['largest_fraction']*100:.1f}% "
             f"| source-null d1/2 primary={null['empirical_d_half_um']} "
             f"legacy={null_legacy['empirical_d_half_um']}")

        entry = {
            "key": arm["key"], "dx_um": arm["dx_um"], "repair": arm["repair"],
            "primary": bool(arm.get("primary")),
            "largest_fraction": conn_used["largest_fraction"],
            "n_components": conn_used["n_components"],
            "tissue_px": int(tissue.sum()),
            "dist_median_um": float(np.median(dist[tissue])),
            "dist_p95_um": float(np.percentile(dist[tissue], 95)),
            "dist_max_um": float(dist[tissue].max()),
            "dist_legacy_median_um": float(np.median(dist_legacy[tissue])),
            "vessel_area_fraction": vm["area_fraction"],
            "source_null": _fit_summary(null),
            "source_null_legacy": _fit_summary(null_legacy),
            "runs": {},
        }

        for flag in flags:
            pde = PDEConfig(convection=True, transvascular_exchange=bool(flag), **vp._PDE)
            for name in drugs:
                t0 = time.time()
                with instrument() as probe:
                    r = vp.analyze_drug(micro, name, alpha, dist, pde,
                                        legacy_distance_um=dist_legacy)
                auc = r["auc_field"]
                rec = {
                    "drug": name, "exchange": bool(flag),
                    "seconds": time.time() - t0,
                    "solver_calls": probe.solver_calls,
                    "exchange_k_calls": probe.exchange_k_calls,
                    "exchange_coefficient_calls": probe.exchange_coefficient_calls,
                    "auc_digest": digest(auc),
                    "auc_sum": float(auc.sum()),
                    "mean_auc": r["mean_auc"],
                    "kill_fraction": r["kill_fraction"],
                    "penetration_index": r["penetration_index"],
                    "L_analytic_um": r["L_analytic_um"],
                    "corr_with_source": float(np.corrcoef(auc[tissue], vasc[tissue])[0, 1]),
                    "primary": _fit_summary(r["auc"]),
                    "legacy": _fit_summary(r["auc_legacy"]),
                    "conc_primary": _fit_summary(r["conc"]),
                    "conc_legacy": _fit_summary(r["conc_legacy"]),
                }
                entry["runs"][f"{name}|{'on' if flag else 'off'}"] = rec
                p = rec["primary"]
                _log(f"ARM {arm['key']} {name:14s} exch={'ON ' if flag else 'OFF'} "
                     f"d1/2={_n(p['empirical_d_half_um'], 1)} L={_n(p['exp_floor_L_um'], 1)} "
                     f"R2={_n(p['exp_floor_r2_linear'], 4)} nbins={p['n_usable_bins']} "
                     f"| legacy d1/2={_n(rec['legacy']['empirical_d_half_um'], 1)} "
                     f"L={_n(rec['legacy']['exp_floor_L_um'], 1)} "
                     f"| corr={rec['corr_with_source']:.3f} "
                     f"solver={probe.solver_calls} exch_k={probe.exchange_k_calls} "
                     f"digest={rec['auc_digest'][:12]} ({rec['seconds']:.0f}s)")
                checkpoint(entry)
        out.append(entry)
        del micro
    return out


# --------------------------------------------------------------------------- #
# Stage 3 -- KDE-bandwidth sweep, both arms
# --------------------------------------------------------------------------- #
def stage_bandwidth(alpha: float, dx_um: float, repair: int, drugs: Sequence[str],
                    flags: Sequence[bool], label: str, checkpoint,
                    bandwidths: Sequence[float] = vp.BANDWIDTH_SWEEP_UM) -> List[Dict]:
    base = reconstruct_real(source="xenium", dx_um=float(dx_um))
    native = np.asarray(base.domain.tissue_mask, dtype=bool)
    mask = vp.repair_tissue_mask(native, repair) if repair > 0 else native
    dom = Domain(nx=base.domain.nx, ny=base.domain.ny, dx=base.domain.dx,
                 tissue_mask=mask)
    dist = vp.direct_vessel_distance_um(dom, vp.endothelial_xy(base.cells))

    rows = []
    for bw in bandwidths:
        fields = build_real_fields(dom, base.cells, bandwidth_um=float(bw))
        micro = Microenvironment(domain=dom, fields=fields, cells=base.cells,
                                 patient_id=base.patient_id, metadata=base.metadata)
        vasc = np.asarray(fields.vascular_density, dtype=np.float64)
        null = vp.profile_fits(vp.distance_profile(vasc, dist, mask))
        row = {"label": label, "bandwidth_um": float(bw),
               "source_null": _fit_summary(null), "runs": {}}
        for flag in flags:
            pde = PDEConfig(convection=True, transvascular_exchange=bool(flag), **vp._PDE)
            for name in drugs:
                t0 = time.time()
                with instrument() as probe:
                    r = vp.analyze_drug(micro, name, alpha, dist, pde)
                auc = r["auc_field"]
                rec = {
                    "drug": name, "exchange": bool(flag),
                    "seconds": time.time() - t0,
                    "solver_calls": probe.solver_calls,
                    "exchange_k_calls": probe.exchange_k_calls,
                    "auc_digest": digest(auc),
                    "corr_with_source": float(np.corrcoef(auc[mask], vasc[mask])[0, 1]),
                    "primary": _fit_summary(r["auc"]),
                }
                row["runs"][f"{name}|{'on' if flag else 'off'}"] = rec
                _log(f"BW[{label}] bw={bw:.0f} {name:14s} exch={'ON ' if flag else 'OFF'} "
                     f"L={_n(rec['primary']['exp_floor_L_um'], 1)} "
                     f"d1/2={_n(rec['primary']['empirical_d_half_um'], 1)} "
                     f"nullL={_n(row['source_null']['exp_floor_L_um'], 1)} "
                     f"corr={rec['corr_with_source']:.3f} exch_k={probe.exchange_k_calls} "
                     f"digest={rec['auc_digest'][:12]} ({rec['seconds']:.0f}s)")
                checkpoint(row)
        rows.append(row)
        del micro, fields
    return rows


# --------------------------------------------------------------------------- #
def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--stage", default="all",
                    choices=["all", "iso", "arms", "bandwidth"])
    ap.add_argument("--arms", default="dx12_repaired,dx12_native,dx30_native")
    ap.add_argument("--flags", default="off,on",
                    help="which exchange arms to run: 'off', 'on' or 'off,on'")
    ap.add_argument("--bw-flags", default="on")
    ap.add_argument("--drugs", default=",".join(DRUGS))
    args = ap.parse_args()

    drugs = tuple(d for d in args.drugs.split(",") if d)
    flags = tuple(f == "on" for f in args.flags.split(",") if f)
    bw_flags = tuple(f == "on" for f in args.bw_flags.split(",") if f)
    want = set(args.arms.split(","))

    payload: Dict = {"generated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                     "default_transvascular_exchange": PDEConfig().transvascular_exchange}

    def checkpoint(_partial=None) -> None:
        with open(args.out, "w") as fh:
            json.dump(_jsonable(payload), fh, indent=1)

    t_all = time.time()
    _log(f"PDEConfig().transvascular_exchange default = "
         f"{PDEConfig().transvascular_exchange}")
    alpha = calibrate_alpha()
    payload["alpha"] = float(alpha)
    _log(f"alpha = {alpha!r}")
    checkpoint()

    if args.stage in ("all", "iso"):
        # mean ECM of the primary arm, exactly as vessel_profile.run() does
        prim, _, _ = vp.build_arm_microenvironment(12.0, 2)
        ecm = float(vp.reconstruction_report(prim)["mean_ecm_density"])
        del prim
        payload["mean_ecm_density"] = ecm
        _log(f"isolated-control ECM = {ecm:.6f}")
        payload["isolated"] = stage_isolated(alpha, ecm, drugs)
        checkpoint()

    if args.stage in ("all", "arms"):
        arms = [a for a in vp.ARMS if a["key"] in want]
        payload["arms"] = stage_arms(alpha, arms, drugs, flags, checkpoint)
        checkpoint()

    if args.stage in ("all", "bandwidth"):
        payload["bandwidth"] = []
        payload["bandwidth"] += stage_bandwidth(
            alpha, 12.0, 2, drugs, bw_flags, "dx12_repaired", checkpoint)
        checkpoint()
        payload["bandwidth"] += stage_bandwidth(
            alpha, 12.0, 0, drugs, bw_flags, "dx12_native", checkpoint)
        checkpoint()

    payload["total_seconds"] = time.time() - t_all
    checkpoint()
    _log(f"DONE in {payload['total_seconds']:.0f}s -> {args.out}")


if __name__ == "__main__":
    main()
